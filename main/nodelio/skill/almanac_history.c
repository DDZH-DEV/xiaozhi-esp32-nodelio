int nl_history_on_day(int month, int day, nl_hist_item_t *out, int cap) {
    if (!out || cap <= 0 || month < 1 || month > 12 || day < 1 || day > 31) {
        return 0;
    }
    const uint16_t md = (uint16_t)(month * 100 + day);
    int n = 0;
    for (size_t i = 0; i < sizeof(kHist) / sizeof(kHist[0]); ++i) {
        if (kHist[i].md != md) {
            continue;
        }
        if (n >= cap) {
            break;
        }
        out[n].year = kHist[i].year;
        out[n].text = kHist[i].text;
        ++n;
    }
    return n;
}
