static int s_mode;

extern "C" const ui_palette_t *ui_palette(void)
{
    return s_mode ? &k_dark : &k_light;
}

extern "C" void ui_palette_set(int mode)
{
    s_mode = mode == 1 ? 1 : 0;
}

extern "C" int ui_palette_is_dark(void)
{
    return s_mode == 1;
}
