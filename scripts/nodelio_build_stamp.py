#!/usr/bin/env python3
"""NodeLio 墙板构建号：按源码指纹升号，非每次编译都涨。

格式：YYYYMMDD.NNN（当天首次改代码为 001，同日再改递增；换日重置为 001）
各 board_id 各记各的序号，互不占用。
内容未变 → 复用该板上次构建号（重编不涨号）
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from datetime import datetime
from pathlib import Path

SCAN_GLOBS = ("**/*.c", "**/*.cc", "**/*.cpp", "**/*.h", "**/*.hpp", "**/*.inc")
# 86 保持原扫描范围，避免已有 .nodelio_build_stamp.json 的指纹被换范围后空涨一号。
BOARD_SCAN = {
    "sila_86": ("main/nodelio", "main/boards/sila"),
    "sila_p4c5_62": ("main/nodelio", "main/boards/sila/sila-p4c5-62"),
    "sila_p4c5_508": ("main/nodelio", "main/boards/sila/sila-p4c5-508"),
}
SKIP_NAMES = {"nodelio_build_stamp.h"}


def default_state_path(root: Path, board: str) -> Path:
    if board == "sila_86":
        return root / ".nodelio_build_stamp.json"
    return root / f".nodelio_build_stamp.{board}.json"


def content_fingerprint(root: Path, scan_dirs: tuple[str, ...]) -> str:
    h = hashlib.sha256()
    files: list[Path] = []
    for rel in scan_dirs:
        base = root / rel
        if not base.is_dir():
            continue
        for pattern in SCAN_GLOBS:
            files.extend(base.glob(pattern))
    for path in sorted({p.resolve() for p in files if p.is_file()}):
        if path.name in SKIP_NAMES:
            continue
        rel = path.relative_to(root).as_posix()
        h.update(rel.encode("utf-8"))
        h.update(b"\0")
        h.update(path.read_bytes())
        h.update(b"\0")
    return h.hexdigest()[:16]


def load_state(path: Path) -> dict:
    if not path.is_file():
        return {}
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}


def write_header(out: Path, stamp: str, fingerprint: str, day: str, serial: int) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    text = (
        "/* Auto-generated by scripts/nodelio_build_stamp.py — do not edit. */\n"
        "#pragma once\n"
        f'#define NODELIO_BUILD_STAMP "{stamp}"\n'
        f'#define NODELIO_BUILD_STAMP_DAY "{day}"\n'
        f"#define NODELIO_BUILD_STAMP_SERIAL {serial}\n"
        f'#define NODELIO_BUILD_CONTENT "{fingerprint}"\n'
    )
    if out.is_file() and out.read_text(encoding="utf-8") == text:
        return
    out.write_text(text, encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    ap.add_argument("--board", choices=sorted(BOARD_SCAN), default="sila_86")
    ap.add_argument(
        "--out",
        type=Path,
        default=None,
        help="generated header path",
    )
    ap.add_argument(
        "--state",
        type=Path,
        default=None,
        help="persistent stamp state json (default: per-board file)",
    )
    args = ap.parse_args()
    root: Path = args.root.resolve()
    out = (args.out or (root / "main" / "nodelio" / "nodelio_build_stamp.h")).resolve()
    state_path = (args.state or default_state_path(root, args.board)).resolve()

    today = datetime.now().strftime("%Y%m%d")
    fp = content_fingerprint(root, BOARD_SCAN[args.board])
    state = load_state(state_path)

    reused = False
    if state.get("content") == fp and state.get("stamp"):
        stamp = str(state["stamp"])
        day = str(state.get("day") or stamp.split(".", 1)[0])
        serial = int(state.get("serial") or 1)
        reused = True
    else:
        if state.get("day") == today:
            serial = int(state.get("serial") or 0) + 1
        else:
            serial = 1
        if serial < 1:
            serial = 1
        if serial > 999:
            print(f"[nodelio-stamp] WARN serial={serial} exceeds 999", file=sys.stderr)
        day = today
        stamp = f"{day}.{serial:03d}"
        state = {
            "day": day,
            "serial": serial,
            "content": fp,
            "stamp": stamp,
        }
        state_path.write_text(json.dumps(state, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    write_header(out, stamp, fp, day, serial)
    action = "reuse" if reused else "bump"
    print(f"[nodelio-stamp] {args.board} {action} {stamp} content={fp}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
